#!/bin/sh
# ============================================================================
# deadline.sh —— 「该不该停」的机械判据，不靠判断力靠退出码
# ============================================================================
# 用法:
#     ./deadline.sh                  # 用默认截止（今天 18:30）
#     ./deadline.sh "23:00"          # 指定今天的截止时刻
#     ./deadline.sh "07:30" --rollover   # 跨午夜：今天过了就算明早 7:30
#
# 退出码（这才是重点，输出只是给人看的）：
#     0  ⇒ 还有时间 ⇒ **必须继续工作**（下一条输出要是工具调用）
#     1  ⇒ 到点了 ⇒ 才允许收尾（校验 → present_files → 总结）
#
# 为什么要它：长时任务里「停」是默认分支，「继续」需要主动做一件事。
# 而「我觉得该汇报了」那个瞬间不会自发触发任何检查 ——
# 把检查变成一个**有退出码的命令**，判断就不再依赖判断力。
#
# ★ 为什么用 `date` 而不是会话注入的 current_time：
#   实测注入值在一次会话里跳 22:20→23:06→23:55→00:03→09:37→10:51→12:59，
#   与系统时钟不同步。曾据此在交付文档写下「12:45」，
#   而真实时间是 10:52 —— 报告了一个尚未到来的时刻。
#   时间戳也是数字，也必须可核验。
# ============================================================================

# --- 2026-10-18 补充 -------------------------------------------------------
# 本脚本已被 `tools/longrun_guard.py`（项目根）取代：后者除了判到点，还知道
# 待办池与心跳，并且 `gate` 非 0 退出就是「不许收工」。
# 教训：本脚本存在了 3 天却一次没被调用（埋在子目录里，没人路过）。
# 这里加注是为了避免「两个判据、谁都不生效」；行为一行未改。
# ---------------------------------------------------------------------------

T=""
ROLL=0
for a in "$@"; do
    case "$a" in
        --rollover) ROLL=1 ;;
        -*) echo "deadline.sh: 未知选项 $a" >&2; exit 2 ;;
        *) T="$a" ;;
    esac
done
[ -n "$T" ] || T="18:30"

NOW=$(date +%s)
END=$(date -d "today $T:00" +%s 2>/dev/null)

if [ -z "$END" ]; then
    echo "deadline.sh: 无法解析截止时刻 '$T'（期望 HH:MM）" >&2
    exit 2
fi

# ★★★ 这里原先无条件顺延到明天 —— 自测时抓到的**机制自身的 bug**：
#   那样写的话，本子里 deadline.sh **永远不可能返回 1**：
#   到 18:31 跑它会说「今天 18:30 已过 ⇒ 按明天算，还剩 658 分钟」
#   ⇒ 让我一直干活，正好和我要防的「该停不停」**完全相反**。
#   正确做法：默认**只在今天内判定**（过点就是到点，返回 1）；
#   只有显式 --rollover 才允许跨午夜 —— 那对应
#   「工作到明天早上 7:30」这种说法（本次任务的第一轮就出现过）。
if [ "$NOW" -ge "$END" ]; then
    if [ "$ROLL" -eq 1 ]; then
        END=$(date -d "tomorrow $T:00" +%s 2>/dev/null)
        if [ -z "$END" ]; then
            echo "deadline.sh: 无法顺延到明天" >&2
            exit 2
        fi
        NOTE="（今天已过，--rollover ⇒ 按明天算）"
    else
        printf '真实 %s   截止 %s（今天）   已到点\n' \
            "$(date '+%Y-%m-%d %H:%M:%S')" "$T"
        echo "→ 退出码 1：已过今天的截止时刻，可以收尾"
        echo "   （若这确实是跨午夜的任务，加 --rollover 重新判定）"
        exit 1
    fi
else
    NOTE="（今天内）"
fi

REM=$(( (END - NOW) / 60 ))
printf '真实 %s   截止 %s%s   还剩 %d 分钟\n' \
    "$(date '+%Y-%m-%d %H:%M:%S')" "$T" "$NOTE" "$REM"

if [ "$REM" -gt 0 ]; then
    echo "→ 退出码 0：**还没到点，必须继续**（下一条输出要是工具调用，不是文字）"
    exit 0
else
    echo "→ 退出码 1：到点了，可以收尾（先校验，再 present_files，再总结）"
    exit 1
fi