/**
 * IDCT 的余弦基：`COS[u*8+x] = (u==0 ? 1/√2 : 1) * cos((2x+1)uπ/16) / 2`。
 *
 * ★ 为什么除 2 写进基里：一维 IDCT 的定义是 `f(x) = 1/2 Σ c(u)F(u)cos(...)`，
 *   行、列各做一次 ⇒ 总缩放 1/4，与二维定义的 1/4 系数一致。
 *   把缩放放在基里，就不需要在最后乘一个"神秘常数"（那种常数最容易写错且看不出来）。
 */
export const COS = (() => {
  const t = new Float64Array(64);
  for (let u = 0; u < 8; u++) {
    for (let x = 0; x < 8; x++) {
      t[u * 8 + x] = ((u === 0 ? Math.SQRT1_2 : 1) * Math.cos(((2 * x + 1) * u * Math.PI) / 16)) / 2;
    }
  }
  return t;
})();
